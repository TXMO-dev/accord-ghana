import {writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {rpc,Networks,Contract,Asset,StrKey,scValToNative} from '@stellar/stellar-sdk';
const [contractId,expectedSha,deploymentHash]=process.argv.slice(2);
if(!StrKey.isValidContract(contractId||'')||!/^[a-f0-9]{64}$/.test(expectedSha||'')||!/^[a-f0-9]{64}$/.test(deploymentHash||''))throw Error('Usage: node scripts/verify-mainnet.mjs C_CONTRACT REVIEWED_WASM_SHA256 DEPLOYMENT_TX_HASH');
const endpoint=process.env.MAINNET_RPC_URL;
if(!endpoint||new URL(endpoint).protocol!=='https:')throw Error('Set MAINNET_RPC_URL to an HTTPS Mainnet RPC.');
const server=new rpc.Server(endpoint);
if((await server.getNetwork()).passphrase!==Networks.PUBLIC)throw Error('RPC is not Mainnet.');
const receipt=await server.getTransaction(deploymentHash);
if(receipt.status!=='SUCCESS'||!receipt.returnValue||scValToNative(receipt.returnValue)!==contractId)throw Error('Receipt does not confirm this deployment.');
const wasm=await server.getContractWasmByContractId(contractId);
const actualSha=createHash('sha256').update(wasm).digest('hex');
if(actualSha!==expectedSha)throw Error('Deployed code differs from the reviewed WASM.');
const ledger=await server.getLedgerEntries(new Contract(contractId).getFootprint());
const instance=ledger.entries[0]?.val.contractData.val.instance;
if(!instance)throw Error('Active contract instance unavailable.');
const entry=instance.storage?.find(item=>JSON.stringify(scValToNative(item.key))==='["Asset"]');
const assetId=entry&&scValToNative(entry.val);
if(assetId!==Asset.native().contractId(Networks.PUBLIC))throw Error('Constructor asset is not Mainnet XLM.');
await mkdir('work/mainnet',{recursive:true});
await writeFile('work/mainnet/verified-deployment.json',JSON.stringify({network:'MAINNET',contractId,assetId,wasmSha256:actualSha,deploymentHash,verifiedAt:new Date().toISOString(),ledger:ledger.latestLedger,active:false,remaining:['Mainnet app activation','Real-value lifecycle and settlement signoff']},null,2));
console.log('Mainnet code, constructor asset and deployment receipt verified. Report saved; public app configuration unchanged.');
